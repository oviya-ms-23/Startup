import React, { useState } from 'react';
import { ShieldCheck, CheckSquare, AlertTriangle, Copy, Check, Share2 } from 'lucide-react';

export default function VerificationSteps({ steps, precautions, rawText, riskLevel, riskScore }) {
  const [copied, setCopied] = useState(false);

  const handleCopyReport = () => {
    const report = `[TrustLens Risk Assessment Report]
Risk Level: ${riskLevel} (Threat Index: ${riskScore}/100)
Date: ${new Date().toLocaleString()}

Verified Guidance:
${steps.map((s, i) => `${i + 1}. ${s.title}: ${s.detail}`).join('\n')}

Core Safety Precautions:
${precautions.map(p => `• ${p}`).join('\n')}

Disclaimer: Generated by TrustLens Digital Safety Assistant. Independent verification always recommended.`;

    navigator.clipboard.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
      
      {/* Recommended Verification Protocol */}
      <div className="p-5 rounded-2xl glass-panel border border-slate-800 flex flex-col justify-between">
        <div>
          <div className="flex items-center justify-between mb-3">
            <h4 className="text-xs font-bold uppercase tracking-wider font-mono text-slate-300 flex items-center gap-2">
              <ShieldCheck className="w-4 h-4 text-electric-400" />
              <span>Recommended Verification Steps</span>
            </h4>
          </div>

          <div className="space-y-3">
            {steps.map((step, idx) => (
              <div key={idx} className="flex items-start gap-3 p-3 rounded-xl bg-slate-900/60 border border-slate-800/80">
                <span className="w-5 h-5 rounded-full bg-electric-500/10 text-electric-300 border border-electric-500/30 text-xs font-bold font-mono flex items-center justify-center shrink-0 mt-0.5">
                  {idx + 1}
                </span>
                <div>
                  <h5 className="text-xs font-semibold text-slate-200">
                    {step.title}
                  </h5>
                  <p className="text-xs text-slate-400 mt-0.5 leading-relaxed">
                    {step.detail}
                  </p>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Copy Report Button */}
        <div className="mt-4 pt-3 border-t border-slate-800/80">
          <button
            onClick={handleCopyReport}
            className="w-full flex items-center justify-center gap-2 py-2 px-3 rounded-lg text-xs font-semibold font-mono bg-slate-850 hover:bg-slate-800 text-slate-200 border border-slate-700/80 transition-colors"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-300">Analysis Copied to Clipboard</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-400" />
                <span>Copy Threat Assessment Summary</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Safety Precautions */}
      <div className="p-5 rounded-2xl glass-panel border border-slate-800 flex flex-col justify-between">
        <div>
          <div className="flex items-center gap-2 mb-3">
            <AlertTriangle className="w-4 h-4 text-amber-400" />
            <h4 className="text-xs font-bold uppercase tracking-wider font-mono text-slate-300">
              Immediate Safety Precautions
            </h4>
          </div>

          <ul className="space-y-2.5">
            {precautions.map((precaution, idx) => (
              <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-300 leading-relaxed">
                <span className="w-1.5 h-1.5 rounded-full bg-amber-400 shrink-0 mt-1.5" />
                <span>{precaution}</span>
              </li>
            ))}
          </ul>
        </div>

        <div className="mt-4 p-3 rounded-xl bg-rose-950/20 border border-rose-500/20 flex items-center justify-between text-xs">
          <span className="text-rose-200 font-medium">Already transferred funds?</span>
          <a
            href="#action-centre"
            className="px-2.5 py-1 rounded bg-rose-500/20 hover:bg-rose-500/30 text-rose-300 border border-rose-500/30 font-semibold transition-colors"
          >
            Open 1930 Guide
          </a>
        </div>
      </div>

    </div>
  );
}
